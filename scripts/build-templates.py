#!/usr/bin/env python3
"""
Build app/jcard-templates.js from the J-card scans in JCards/JPEG.

Each template's text-box layout lives in JCards/layouts.json (pixel
rectangles measured on the original JPEG). To add a new template:
  1. Drop the scan into JCards/JPEG (scan it with the 4" side vertical
     for rotated cards, or horizontal for upright cards).
  2. Add an entry to JCards/layouts.json — name, brand, rot (-90, 0 or 90),
     pitchPx (ruled-line spacing in px, or null) and A / B / T rectangles
     as [x0, y0, x1, y1] in image pixels.
  3. Run:  python3 scripts/build-templates.py
           node scripts/build-standalone.js

Requires Pillow (pip install pillow).
"""
import base64, io, json, os, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JPEG_DIR = os.path.join(ROOT, 'JCards', 'JPEG')
LAYOUTS = os.path.join(ROOT, 'JCards', 'layouts.json')
OUT = os.path.join(ROOT, 'app', 'jcard-templates.js')

layouts = json.load(open(LAYOUTS))
entries = []
for fn, c in layouts.items():
    path = os.path.join(JPEG_DIR, fn)
    if not os.path.exists(path):
        print('missing image, skipped:', fn, file=sys.stderr)
        continue
    im = Image.open(path).convert('RGB')
    W, H = im.size
    # A J-card is 4" along the cassette's length. Most scans are 200 dpi;
    # otherwise derive the dpi from that 4" dimension.
    along = H if c['rot'] else W
    dpi = 200 if 3.75 <= along / 200 <= 4.25 else along / 4.0
    buf = io.BytesIO()
    im.save(buf, 'JPEG', quality=82, optimize=True, progressive=True)
    fr = lambda r: [round(r[0] / W, 4), round(r[1] / H, 4),
                    round((r[2] - r[0]) / W, 4), round((r[3] - r[1]) / H, 4)]
    entries.append(dict(
        id=fn.rsplit('.', 1)[0], name=c['name'], brand=c['brand'],
        wIn=round(W / dpi, 3), hIn=round(H / dpi, 3), rot=c['rot'],
        pitchIn=round(c['pitchPx'] / dpi, 4) if c.get('pitchPx') else None,
        A=fr(c['A']), B=fr(c['B']), T=fr(c['T']),
        src='data:image/jpeg;base64,' + base64.b64encode(buf.getvalue()).decode()))

entries.sort(key=lambda e: e['name'].lower())
js = ('/* Built-in J-card templates — generated by scripts/build-templates.py from JCards/. Do not edit by hand. */\n'
      'window.JCARD_TEMPLATES = [\n' +
      ',\n'.join(json.dumps(e, separators=(',', ':')) for e in entries) + '\n];\n')
open(OUT, 'w').write(js)
print(f'Wrote {len(entries)} templates to {os.path.relpath(OUT, ROOT)} ({len(js) / 1e6:.1f} MB)')
